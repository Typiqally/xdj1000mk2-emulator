pub fn rect(data: [f32; 4], origin: Pos2, scale: f32) -> Rect {
    Rect::from_center_size(
        origin + Vec2::new(data[0], data[1]) * scale,
        Vec2::new(data[2], data[3]) * scale,
    )
}
pub fn box_rect(data: [f32; 4], origin: Pos2, scale: f32) -> Rect {
    Rect::from_min_size(
        origin + Vec2::new(data[0], data[1]) * scale,
        Vec2::new(data[2], data[3]) * scale,
    )
}

